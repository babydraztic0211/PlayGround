export function oreCost(cost) {
  const out = [];
  for (const key of ORE_ORDER) {
    if (cost[key]) out.push({ key, amount: cost[key], ...ORES[key] });
  }
  return out;
}

export function formatStat(def, level) {
  const value = STATS[def.statKey][level];
  if (def.statKey === 'yieldMult') return `${value.toFixed(2).replace(/0$/, '')}×`;
  if (def.statKey === 'swingCooldown') return `${value.toFixed(2)}s`;
  if (def.statKey === 'maxHp') return `${Math.round(value)}`;
  return `${value.toFixed(1).replace(/\.0$/, '')}`;
}
